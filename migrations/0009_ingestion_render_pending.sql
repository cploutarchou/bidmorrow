-- 0009_ingestion_render_pending — ADR-0009 §1: render-pending exhaustion is
-- a tracked skip, not a systemic fetch failure.
--
-- Purpose: `ingestion_runs.notices_render_pending` is a new run-level
-- counter, split out of `notices_fetch_failed` (ADR-0008 §5/ADR-0009 §1).
-- Render-pending exhaustion (`NOTICE_RENDER_PENDING`: TED accepted the
-- request and queued the render but did not serve it within the visit
-- budget) is the origin *cooperating*, not refusing — unlike a genuine
-- `NOTICE_FETCH_HTTP_*` / `NOTICE_FETCH_NETWORK_ERROR` failure. Isolating it
-- means `notices_fetch_failed` reverts to "genuine fetch failures only"
-- (its pre-ADR-0008-Amendment-§A1 semantics, which its consumers — watchdog
-- condition (iii), admin ingestion views — were designed around), and
-- `notices_render_pending` never contributes to the ADR-0008 §2 systemic
-- fetch-failure threshold. Both paths still write the `ingestion_errors`
-- row and the idempotent `ingestion_fetch_retries` upsert — no skipped
-- notice ever loses its retry row.
--
-- `ingestion_runs` is a global operational table (no `organization_id`),
-- consistent with the other ingestion-ops tables in this file
-- (`ingestion_checkpoints`, `ingestion_errors`, `ingestion_fetch_retries`,
-- `source_snapshots`) — docs/security.md C6 exempts this class of table;
-- see the module header comment in packages/db/src/schema/ingestion.ts and
-- packages/db/src/repositories/ingestion.ts.
--
-- Cost/size: ADR-0009 (Consequences) projects ~8 bytes x ~730 run rows/year
-- ≈ 6 KB/year — noise against the 10 GB D1 cap (ADR-0003 headroom rule,
-- docs/cost-model.md).
--
-- Additive only: one ALTER TABLE ... ADD COLUMN with a DEFAULT, so the
