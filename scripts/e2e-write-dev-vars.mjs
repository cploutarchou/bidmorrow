#!/usr/bin/env node
/**
 * Phase 12 stage A: generates `apps/worker/.dev.vars` for a Playwright E2E
 * run only. Git-ignored (`.gitignore`), regenerated on every `pnpm
 * test:e2e` run so no stale local `.dev.vars` a developer already has can
 * silently be reused with the wrong flags. Every value is a clearly-fake
 * local secret — never a real credential (HUMAN_DECISION_BLOCKERS.md items
 * 3/4/5). `E2E_TEST_HOOKS=true` is the whole point of this file: it double-
 * gates (with `APP_ENV=local`) the test-only auth-email mailbox capture and
 * `/api/test/*` routes (`apps/worker/src/test-hooks-gate.ts`) that the E2E
 * specs depend on. `RESEND_API_KEY`/`STRIPE_SECRET_KEY` etc. are left unset
 * on purpose — the E2E suite never talks to a real network, and the billing
 * spec asserts the honest "not configured" / "no subscription" state that
 * results.
 */
import { randomBytes } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const secret = randomBytes(32).toString('base64');

const content = `# AUTO-GENERATED by scripts/e2e-write-dev-vars.mjs for Playwright E2E runs.
# Git-ignored — regenerated on every \`pnpm test:e2e\`. Do not hand-edit.
# Unconfigured optionals (RESEND_API_KEY, EMAIL_FROM, STRIPE_*, ADMIN_EMAILS)
# are OMITTED, never written as empty assignments: \`KEY=\` yields an empty
# STRING, which is !== undefined and silently flips every "configured vs.
# fallback" provider check (auth email, digest email, billing) the app makes.
APP_ENV=local
APP_BASE_URL=http://127.0.0.1:8787
BETTER_AUTH_SECRET=${secret}
BETTER_AUTH_URL=http://127.0.0.1:8787
E2E_TEST_HOOKS=true
`;

const target = fileURLToPath(new URL('../apps/worker/.dev.vars', import.meta.url));
writeFileSync(target, content, { mode: 0o600 });
console.log(`wrote ${target}`);
